import '@primer/brand-primitives/lib/design-tokens/css/tokens/functional/components/feature-comparison-table/colors-with-modes.css'

/**
 * Main stylesheet (as a CSS Module)
 */
import styles from './FeatureComparisonTable.module.css'
import gridlineStyles from '../component-helpers/shared.module.css'

export type FeatureComparisonTableProps = PropsWithChildren<
  BaseProps<HTMLDivElement> &
    Omit<React.HTMLAttributes<HTMLDivElement>, 'aria-label' | 'aria-labelledby'> & {
      'data-testid'?: string
      /** Overrides accessible labels generated by the table. */
      labels?: {
        collapseAllGroups?: string
        expandAllGroups?: string
        featureColumn?: string
        showDescription?: string
        hideDescription?: string
      }
    }
>

type GroupOpenState = {
  breakpoint: BreakpointCategory
  groups: Record<string, {signature: string; open: boolean}>
}

const toggleAllGroupsControlKey = 'toggleAllGroups'

const FeatureComparisonTableRoot = forwardRef<HTMLDivElement, FeatureComparisonTableProps>(
  (
    {
      animate,
      children,
      className,
      labels: {
        collapseAllGroups = 'Collapse all features',
        expandAllGroups = 'Expand all features',
        featureColumn = 'Feature',
        showDescription = 'Show description',
        hideDescription = 'Hide description',
      } = {},
      onBlur,
      onFocus,
      style,
      'data-testid': testId,
      ...rest
    },
    ref,
  ) => {
    const instanceId = useId()
    const {classes: animationClasses, styles: animationInlineStyles} = useAnimation(animate)
    const {width, isMedium: isRegular, isXLarge: isWide} = useWindowSize()
    const [breakpoint, setBreakpoint] = useState<BreakpointCategory>('narrow')
    const tableRef = useRef<HTMLTableElement>(null)
    const narrowControlsRef = useRef<Record<string, HTMLElement | null>>({})
    const tableControlsRef = useRef<Record<string, HTMLElement | null>>({})
    const rowControlGroupIdentitiesRef = useRef<Record<string, string>>({})
    const rowDescriptionsOpenRef = useRef<Record<string, boolean>>({})
    const previousBreakpointRef = useRef(breakpoint)
    const blurredElementRef = useRef<HTMLElement | null>(null)
    const focusedControlKeyRef = useRef<string | undefined>(undefined)
    const rootChildren = React.Children.toArray(children)
    const heading = getChildrenOfType(rootChildren, FeatureComparisonTableHeading).at(-1)
    const allItems = getChildrenOfType(rootChildren, FeatureComparisonTableItem)
    const items = allItems.slice(0, 4)
    const groups = getChildrenOfType(rootChildren, FeatureComparisonTableGroup)
    const hasLabels = items.some(hasItemLabel)
    const hasStickyHeaders = useFeatureComparisonTableStickyHeaders(tableRef, breakpoint === 'wide', items.length > 0)
    const [groupOpenState, setGroupOpenState] = useState<GroupOpenState>({breakpoint, groups: {}})

    // Expanded state resets to each group's defaults whenever the layout changes.
    if (groupOpenState.breakpoint !== breakpoint) {
      setGroupOpenState({breakpoint, groups: {}})
    }

    const getExpandedSignature = (expanded: FeatureComparisonTableGroupProps['expanded']) =>
      typeof expanded === 'boolean'
        ? String(expanded)
        : expanded
        ? `${expanded.narrow}-${expanded.regular}-${expanded.wide}`
        : 'default'
    const groupStates = groups.map(group => {
      const {expanded} = group.props
      const identity = String(group.key)
      const signature = getExpandedSignature(expanded)
      const state = groupOpenState.breakpoint === breakpoint ? groupOpenState.groups[identity] : undefined
      const defaultOpen =
        typeof expanded === 'boolean' ? expanded : expanded ? expanded[breakpoint] : breakpoint !== 'narrow'
      return {identity, signature, open: state?.signature === signature ? state.open : defaultOpen}
    })
    const allGroupsCollapsed = groupStates.every(({open}) => !open)

    const setGroupsOpen = (nextStates: typeof groupStates) =>
      setGroupOpenState(previous => {
        const previousGroups = previous.breakpoint === breakpoint ? previous.groups : {}
        const nextGroups = {...previousGroups}
        for (const {identity, signature, open} of nextStates) nextGroups[identity] = {signature, open}
        return {breakpoint, groups: nextGroups}
      })

    const handleToggleAllGroups = () =>
      setGroupsOpen(groupStates.map(groupState => ({...groupState, open: allGroupsCollapsed})))

    useEffect(() => {
      if (process.env.NODE_ENV !== 'production' && allItems.length > 4) {
        // eslint-disable-next-line no-console
        console.warn(
          `FeatureComparisonTable: supports at most 4 Item children, but received ${allItems.length}. Extra items are ignored.`,
        )
      }
    }, [allItems.length])

    useEffect(() => {
      const nextBreakpoint = isWide ? 'wide' : isRegular ? 'regular' : 'narrow'
      const previous = previousBreakpointRef.current

      if ((previous === 'wide') !== (nextBreakpoint === 'wide')) {
        // Capture focus before the previous projection unmounts and clears its refs.
        const activeElement =
          document.activeElement === document.body ? blurredElementRef.current : document.activeElement
        const previousControls = previous === 'wide' ? tableControlsRef.current : narrowControlsRef.current
        focusedControlKeyRef.current = Object.entries(previousControls).find(
          ([, control]) => control !== null && control === activeElement,
        )?.[0]
      }
      blurredElementRef.current = null
      setBreakpoint(nextBreakpoint)
    }, [isRegular, isWide, width])

    useIsomorphicLayoutEffect(() => {
      const previous = previousBreakpointRef.current
      previousBreakpointRef.current = breakpoint
      blurredElementRef.current = null
      if ((previous === 'wide') === (breakpoint === 'wide')) return
      const nextControls = breakpoint === 'wide' ? tableControlsRef.current : narrowControlsRef.current
      const focusedControlKey = focusedControlKeyRef.current
      focusedControlKeyRef.current = undefined
      if (!focusedControlKey) return
      const control = nextControls[focusedControlKey]
      control?.focus()
      // Rows in a collapsed group can't take focus, so fall back to the group's control.
      const groupIdentity = rowControlGroupIdentitiesRef.current[focusedControlKey]
      if (groupIdentity && document.activeElement !== control) nextControls[groupIdentity]?.focus()
    }, [breakpoint])

    const handleFocus = (event: React.FocusEvent<HTMLDivElement>) => {
      const table = tableRef.current
      const target = event.target
      if (hasStickyHeaders && breakpoint === 'wide' && table?.contains(target) && !target.closest('thead')) {
        if (target.closest('tbody')) {
          const stickyHeaderBottom = Array.from(table.querySelectorAll<HTMLTableCellElement>('thead th')).reduce(
            (maximumBottom, header) => {
              const rect = header.getBoundingClientRect()
              const isVisible = rect.bottom > 0 && rect.top < window.innerHeight
              return isVisible ? Math.max(maximumBottom, rect.bottom) : maximumBottom
            },
            0,
          )
          const targetRect = target.getBoundingClientRect()
          const targetStyles = window.getComputedStyle(target)
          const focusIndicatorClearance = Math.max(
            0,
            (Number.parseFloat(targetStyles.outlineWidth) || 0) + (Number.parseFloat(targetStyles.outlineOffset) || 0),
          )
          if (
            stickyHeaderBottom > 0 &&
            targetRect.bottom > 0 &&
            targetRect.top - focusIndicatorClearance < stickyHeaderBottom
          ) {
            window.scrollBy({top: targetRect.top - stickyHeaderBottom - focusIndicatorClearance, behavior: 'instant'})
          }
        }
      }
      onFocus?.(event)
    }

    if (items.length === 0) return null
    if (!heading && process.env.NODE_ENV !== 'production') {
      // eslint-disable-next-line no-console
      console.warn('FeatureComparisonTable: a root FeatureComparisonTable.Heading child is required.')
    }

    const tableContext: TableContextValue = {
      instanceId,
      breakpoint,
      items,
      itemIndex: 0,
      groupIndex: 0,
      groupIdentity: '',
      groupOpen: false,
      onGroupOpenChange: () => {},
      rowIdentity: '',
      narrowControlsRef,
      tableControlsRef,
      rowControlGroupIdentitiesRef,
      rowDescriptionsOpenRef,
      descriptionToggleLabels: {show: showDescription, hide: hideDescription},
    }
    const groupElements = groups.map((group, index) => (
      <TableContext.Provider
        value={{
          ...tableContext,
          groupIndex: index,
          groupIdentity: groupStates[index].identity,
          groupOpen: groupStates[index].open,
          onGroupOpenChange: open => {
            if (open !== groupStates[index].open) setGroupsOpen([{...groupStates[index], open}])
          },
        }}
        key={group.key}
      >
        {group}
      </TableContext.Provider>
    ))
    const toggleAllGroupsButton =
      groups.length > 0 ? (
        <Button
          onClick={handleToggleAllGroups}
          ref={(element: HTMLButtonElement | null) => {
            ;(breakpoint === 'wide' ? tableControlsRef : narrowControlsRef).current[toggleAllGroupsControlKey] = element
          }}
          size="small"
          trailingVisual={allGroupsCollapsed ? ChevronDownIcon : ChevronUpIcon}
          type="button"
          variant="subtle"
        >
          {allGroupsCollapsed ? expandAllGroups : collapseAllGroups}
        </Button>
      ) : null
    const headingId = heading?.props.id || `${instanceId}-heading`
    const columnHeadingId = heading ? headingId : `${instanceId}-feature-column`

    return (
      <TableContext.Provider value={tableContext}>
        <div
          className={clsx(
            styles.FeatureComparisonTable,
            gridlineStyles.gridline,
            items.length > 1 && styles[`FeatureComparisonTable--items${items.length}`],
            hasStickyHeaders && styles['FeatureComparisonTable--stickyHeaders'],
            animationClasses,
            className,
          )}
          data-testid={testId || testIds.root}
          ref={ref}
          onBlur={event => {
            if (window.innerWidth !== width || Boolean(isWide) !== (breakpoint === 'wide'))
              blurredElementRef.current = event.target
            onBlur?.(event)
          }}
          onFocus={handleFocus}
          style={{...animationInlineStyles, ...style}}
          {...rest}
        >
          {breakpoint !== 'wide' ? (
            <div className={styles.FeatureComparisonTable__narrow} data-testid={testIds.narrow}>
              {heading || toggleAllGroupsButton ? (
                <div className={clsx(styles.FeatureComparisonTable__narrowHeading, gridlineStyles.gridline)}>
                  {heading}
                  {toggleAllGroupsButton}
                </div>
              ) : null}
              {groupElements}
            </div>
          ) : (
            <table
              aria-labelledby={heading ? headingId : undefined}
              className={styles.FeatureComparisonTable__table}
              data-testid={testIds.table}
              ref={tableRef}
            >
              <colgroup>
                <col className={styles.FeatureComparisonTable__featureColumn} />
                {items.map(item => (
                  <col key={item.key} />
                ))}
              </colgroup>
              <thead className={styles.FeatureComparisonTable__head}>
                <tr
                  className={clsx(
                    groups.length > 0 && gridlineStyles.gridline,
                    styles.FeatureComparisonTable__headingGrid,
                    hasLabels && styles['FeatureComparisonTable__headingGrid--hasLabel'],
                  )}
                >
                  <th
                    aria-labelledby={toggleAllGroupsButton ? columnHeadingId : undefined}
                    className={clsx(
                      styles.FeatureComparisonTable__headerCell,
                      hasLabels && styles['FeatureComparisonTable__headerCell--hasLabel'],
                    )}
                    scope="col"
                  >
                    {toggleAllGroupsButton ? (
                      <div
                        className={clsx(
                          styles.FeatureComparisonTable__tableHeadingContent,
                          hasLabels && styles['FeatureComparisonTable__tableHeadingContent--hasLabel'],
                        )}
                      >
                        {heading ?? (
                          <span className="visually-hidden" id={columnHeadingId}>
                            {featureColumn}
                          </span>
                        )}
                        {toggleAllGroupsButton}
                      </div>
                    ) : heading ? (
                      React.cloneElement(heading, {
                        className: clsx(
                          heading.props.className,
                          styles.FeatureComparisonTable__tableHeading,
                          hasLabels && styles['FeatureComparisonTable__tableHeading--hasLabel'],
                        ),
                      })
                    ) : (
                      <span className="visually-hidden">{featureColumn}</span>
                    )}
                  </th>
                  {items.map((item, index) => (
                    <th
                      className={clsx(
                        styles.FeatureComparisonTable__headerCell,
                        hasLabels && styles['FeatureComparisonTable__headerCell--hasLabel'],
                        hasItemLabel(item) && styles.FeatureComparisonTable__highlightedColumn,
                      )}
                      scope="col"
                      key={item.key}
                    >
                      <TableContext.Provider value={{...tableContext, itemIndex: index + 1}}>
                        {item}
                      </TableContext.Provider>
                    </th>
                  ))}
                </tr>
              </thead>
              {groupElements}
            </table>
          )}
        </div>
      </TableContext.Provider>
    )
  },
)

